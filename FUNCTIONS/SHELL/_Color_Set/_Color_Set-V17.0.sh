_Color_Set() {
	if [ "$COLORS_ON" = "1" ]; then
		C_RESET=$'\033[0m'
		C_BOLD=$'\033[1m'
		C_DIM=$'\033[2m'
		C_UNDERLINE=$'\033[4m'
		C_RED=$'\033[31m'
		C_GREEN=$'\033[32m'
		C_YELLOW=$'\033[33m'
		C_BLUE=$'\033[34m'
		C_MAGENTA=$'\033[35m'
		C_CYAN=$'\033[36m'
		C_WHITE=$'\033[37m'
		C_GRAY=$'\033[90m'
	else
		C_RESET=''
		C_BOLD=''
		C_DIM=''
		C_UNDERLINE=''
		C_RED=''
		C_GREEN=''
		C_YELLOW=''
		C_BLUE=''
		C_MAGENTA=''
		C_CYAN=''
		C_WHITE=''
		C_GRAY=''
	fi
}
